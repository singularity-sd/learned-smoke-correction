"""Reproduces the study by running the original scripts in code/ in their historical order.

1. code/refinement/development.py        - fit of the eight filter weights, choice on 12 development scenes
2. code/refinement/confirmation.py        - first test, 64 scenes, reference 144x144 (criterion not met)
3. code/refinement/confirmation_fine.py   - test fixed in code/refinement/protocol_fine.md: 64 new scenes,
                                          reference 192x192, parallel 144x144, 256x256 check on 8 scenes
4. code/refinement/make_video_fine.py - draws fig_frame.png (and a comparison video if FFmpeg is installed)

The two earlier designs that did not pass are kept with their own scripts: code/experiment.py (pilot, two-layer
Fourier network after a MacCormack step) and code/retry/experiment.py (spectral corrector on one transport).
All scenes are generated by the code; no download is needed. Requires Python 3.12 with numpy, scipy and
opencv-python-headless. Timings depend on the CPU (reported: AMD Ryzen 5 5625U, one thread).
"""

import os
import runpy
import sys
from pathlib import Path

CODE = Path(__file__).resolve().parent / "code"
for var in ("OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(var, "1")

for step in ["refinement/development.py", "refinement/confirmation.py", "refinement/confirmation_fine.py",
             "refinement/make_video_fine.py"]:
    script = CODE / step
    os.chdir(script.parent)
    sys.path.insert(0, str(script.parent))
    print(f"== {step}", flush=True)
    runpy.run_path(str(script), run_name="__main__")
